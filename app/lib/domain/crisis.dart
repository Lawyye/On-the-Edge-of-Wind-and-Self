/// Распознавание слов, за которыми может стоять угроза жизни, и номера помощи.
///
/// Это не диагностика и не фильтр: запись публикуется в любом случае. Задача
/// одна — в нужный момент показать номер, по которому ответит живой человек.
library;

final List<RegExp> _signals = [
  r'суицид',
  r'самоуби',
  r'(покончить|покончу|покончила|покончил)\s+(с\s+собой|со\s+всем)',
  r'(убить|убью)\s+себя',
  r'не\s+(хочу|хочется)\s+(больше\s+)?жить',
  r'жить\s+не\s+(хочу|хочется)',
  r'(нет|не\s+вижу)\s+смысла\s+(жить|в\s+жизни)',
  r'незачем\s+жить',
  r'хочу\s+(умереть|сдохнуть|исчезнуть\s+навсегда)',
  r'лучше\s+бы\s+(меня\s+не\s+было|я\s+умер)',
  r'(вскрыть|вскрою|порезать|порежу|резать|режу)\s+(себе\s+)?(вены|руки|себя)',
  r'селфхарм|self\s*-?\s*harm',
  r'повес(иться|ишься|ишусь|илась|ился)',
  r'(прыгн|спрыгн)\w*\s+с\s+(крыши|моста|окна|балкона)',
  r'наглота\w*\s+таблет',
  // казахский
  r'өзімді\s+өлтір',
  r'өмір\s+сүргім\s+келмейді',
  r'өлгім\s+келеді',
  // английский
  r'kill\s+myself',
  r'suicid',
  r'want\s+to\s+die',
].map((p) => RegExp(p, caseSensitive: false, unicode: true)).toList();

/// Есть ли в тексте признаки того, что человеку может быть опасно.
bool soundsLikeCrisis(String text) {
  final t = text.toLowerCase().replaceAll('ё', 'е');
  return _signals.any((r) => r.hasMatch(t));
}

class Helpline {
  const Helpline({
    required this.number,
    required this.dial,
    required this.title,
    required this.note,
    required this.region,
  });

  /// Как номер пишется для человека.
  final String number;

  /// Как он набирается: только цифры.
  final String dial;
  final String title;
  final String note;
  final String region;
}

