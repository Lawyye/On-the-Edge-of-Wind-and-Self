import 'dart:math';

/// Придуманные имена для знакомства. Прилагательное согласовано с родом
/// существительного, вместе почти четыреста сочетаний: одинаковое имя у двух
/// новичков подряд случается редко, а если случится — база скажет, и мы
/// предложим другое.
const _masc = (
  adjectives: [
    'Тихий', 'Ночной', 'Северный', 'Дальний', 'Тёплый', 'Сонный', 'Мятный',
    'Пятый', 'Добрый', 'Серый', 'Лунный', 'Последний', 'Синий', 'Медленный',
  ],
  nouns: [
    'Спутник', 'Ветер', 'Маяк', 'Фонарь', 'Провод', 'Сигнал', 'Север',
    'Кот', 'Огонёк', 'Причал', 'Трамвай', 'Чайник', 'Свитер', 'Дождь',
  ],
);

const _fem = (
  adjectives: [
    'Тихая', 'Ночная', 'Северная', 'Дальняя', 'Тёплая', 'Сонная', 'Мятная',
    'Пятая', 'Добрая', 'Серая', 'Лунная', 'Последняя', 'Синяя', 'Медленная',
  ],
  nouns: [
    'Полынь', 'Заря', 'Ромашка', 'Волна', 'Станция', 'Антенна', 'Сова',
    'Звезда', 'Тень', 'Нота', 'Лампа', 'Комета', 'Крыша', 'Птица',
  ],
);

String randomNickname([Random? random]) {
  final r = random ?? Random();
  final set = r.nextBool() ? _masc : _fem;
  return '${set.adjectives[r.nextInt(set.adjectives.length)]} '
      '${set.nouns[r.nextInt(set.nouns.length)]}';
}

/// Те же правила, что у базы: 2–24 знака, без невидимых символов и двойных
/// пробелов. Проверка здесь — чтобы сказать человеку сразу, а не после сети.
String? nicknameProblem(String raw) {
  final name = raw.trim();
  if (name.length < 2) return 'Хотя бы две буквы.';
  if (name.length > 24) return 'Не длиннее 24 знаков.';
  if (RegExp(r'\s\s').hasMatch(name)) return 'Два пробела подряд — лишнее.';
  if (_invisible.hasMatch(name)) return 'В имени есть невидимые символы.';
  return null;
}

/// Управляющие символы, мягкий перенос, нулевые пробелы и знаки, переворачивающие
/// направление текста. Собраны из кодов, а не escape-последовательностями: так
/// исходник остаётся чистым и не прячет в себе сами эти символы.
final RegExp _invisible = RegExp('[${[
  for (var c = 0x00; c <= 0x1F; c++) c,
  0x7F,
  0xAD,
  for (var c = 0x200B; c <= 0x200F; c++) c,
  for (var c = 0x202A; c <= 0x202E; c++) c,
  for (var c = 0x2060; c <= 0x206F; c++) c,
  0xFEFF,
].map((c) => RegExp.escape(String.fromCharCode(c))).join()}]');
