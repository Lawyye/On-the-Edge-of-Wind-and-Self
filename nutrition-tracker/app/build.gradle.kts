// Ключ подписи release: из переменных окружения (CI) или keystore.properties (локально).
// Без него release подписывается отладочным ключом — такой APK не встанет поверх
// версии, подписанной постоянным ключом.
val keystoreProps = Properties().apply {
    val f = rootProject.file("keystore.properties")
    if (f.exists()) f.inputStream().use { load(it) }
}
fun signingValue(env: String, prop: String): String? =
    System.getenv(env)?.takeIf { it.isNotBlank() } ?: keystoreProps.getProperty(prop)?.takeIf { it.isNotBlank() }

val releaseStoreFile = signingValue("NT_KEYSTORE_FILE", "storeFile")
val hasReleaseKey = releaseStoreFile != null && file(releaseStoreFile).exists()

// Ключ USDA для разработки: только в отладочной сборке и только из local.properties.
// В release-APK ключ не попадает; пользователь вводит свой ключ в настройках.
val localProps = Properties().apply {
    val f = rootProject.file("local.properties")
    if (f.exists()) f.inputStream().use { load(it) }
}
val devUsdaKey: String = localProps.getProperty("usda.apiKey", "")

